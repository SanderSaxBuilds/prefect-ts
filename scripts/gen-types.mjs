#!/usr/bin/env node
// Turns components.schemas of the Prefect OpenAPI document into src/schema.ts.
//
//   npm run spec    (saves openapi.json from a running server)
//   npm run types   (rewrites src/schema.ts from openapi.json)

import { readFileSync, writeFileSync } from 'node:fs';

const [input = 'openapi.json', output = 'src/schema.ts'] = process.argv.slice(2);
const spec = JSON.parse(readFileSync(input, 'utf8'));
const schemas = spec.components?.schemas ?? {};

// "EventTrigger-Input" and "EventTrigger-Output" are valid schema names but not valid identifiers.
export const typeName = (name) => name.replace(/[^A-Za-z0-9_]/g, '_');
const refName = (ref) => typeName(decodeURIComponent(ref.split('/').pop()));
const isIdentifier = (key) => /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key);

function doc(schema, indent) {
  const lines = [];
  if (schema.description) lines.push(...String(schema.description).trim().split('\n'));
  if (schema.default !== undefined && typeof schema.default !== 'object') lines.push(`@default ${JSON.stringify(schema.default)}`);
  if (schema.format) lines.push(`Format: ${schema.format}`);
  if (schema.deprecated) lines.push('@deprecated');
  if (lines.length === 0) return '';
  const safe = lines.map((line) => line.replace(/\*\//g, '*\\/').trimEnd());
  if (safe.length === 1) return `${indent}/** ${safe[0]} */\n`;
  return `${indent}/**\n${safe.map((line) => `${indent} * ${line}`.trimEnd()).join('\n')}\n${indent} */\n`;
}

const wrap = (type) => (/[|&]/.test(type) && !/^\(.*\)$/.test(type) ? `(${type})` : type);

function union(types) {
  const unique = [...new Set(types)];
  if (unique.includes('unknown')) return 'unknown';
  return unique.join(' | ');
}

function render(schema, indent = '') {
  if (schema === true || schema === undefined) return 'unknown';
  if (schema === false) return 'never';
  if (typeof schema !== 'object' || schema === null) return 'unknown';
  if (schema.$ref) return refName(schema.$ref);
  if (schema.const !== undefined) return JSON.stringify(schema.const);
  if (schema.enum) return union(schema.enum.map((value) => JSON.stringify(value)));
  if (schema.anyOf) return union(schema.anyOf.map((part) => render(part, indent)));
  if (schema.oneOf) return union(schema.oneOf.map((part) => render(part, indent)));
  if (schema.allOf) {
    const parts = schema.allOf.map((part) => wrap(render(part, indent)));
    return parts.length === 1 ? parts[0] : parts.join(' & ');
  }
  if (Array.isArray(schema.type)) {
    return union(schema.type.map((type) => render({ ...schema, type }, indent)));
  }
  switch (schema.type) {
    case 'string':
      return 'string';
    case 'integer':
    case 'number':
      return 'number';
    case 'boolean':
      return 'boolean';
    case 'null':
      return 'null';
    case 'array': {
      if (schema.prefixItems) {
        const items = schema.prefixItems.map((item) => render(item, indent));
        return `[${items.join(', ')}]`;
      }
      return `${wrap(render(schema.items, indent))}[]`;
    }
    case 'object':
    case undefined: {
      if (schema.properties) return objectType(schema, indent);
      if (schema.type === undefined) return 'unknown';
      if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
        return `Record<string, ${render(schema.additionalProperties, indent)}>`;
      }
      return 'Record<string, unknown>';
    }
    default:
      return 'unknown';
  }
}

function objectType(schema, indent) {
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  let body = '{\n';
  for (const [key, property] of Object.entries(schema.properties)) {
    const name = isIdentifier(key) ? key : JSON.stringify(key);
    body += doc(property, inner);
    body += `${inner}${name}${required.has(key) ? '' : '?'}: ${render(property, inner)};\n`;
  }
  const extra = schema.additionalProperties;
  if (extra && extra !== false) {
    body += `${inner}[key: string]: unknown;\n`;
  }
  return `${body}${indent}}`;
}

let out = `// Generated by scripts/gen-types.mjs from openapi.json (${spec.info?.title ?? 'OpenAPI'}).\n`;
out += '// Do not edit by hand. Run `npm run types` after refreshing the spec.\n\n';
for (const name of Object.keys(schemas).sort()) {
  const schema = schemas[name];
  const id = typeName(name);
  out += doc(schema, '');
  if (schema.properties && !schema.anyOf && !schema.oneOf && !schema.allOf) {
    out += `export interface ${id} ${objectType(schema, '')}\n\n`;
  } else {
    out += `export type ${id} = ${render(schema, '')};\n\n`;
  }
}

writeFileSync(output, out);
console.log(`wrote ${Object.keys(schemas).length} types to ${output}`);
